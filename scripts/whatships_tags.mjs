// whatships_tags.mjs: merges the visual tags of every poster (refs/whatships/tags/gNNN.json, written by the tagging pass
// over the grids from whatships_grids.mjs) into refs/whatships/visual.json, and writes the whole-catalog breakdown to
// refs/whatships/visual.md. Fails if any catalog slug is untagged, tagged twice, or has a value outside the taxonomy.
//   node scripts/whatships_tags.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const DIR = 'refs/whatships';
const ENUM = {
  medium: ['ui_polished', 'ui_screen', 'kinetic_type', 'graphic_2d', 'illustration', 'abstract', 'render_3d', 'live_people', 'live_product', 'live_scene', 'blank'],
  bg: ['dark', 'light', 'gradient', 'colorful', 'photo', 'none'],
  text: ['none', 'some', 'dominant'],
  feasible: ['yes', 'partial', 'no', 'unknown'],
};
const OVERLAYS = ['text', 'ui', 'logo', 'cursor', 'captions', 'graphics'];
// Can code make it? Derived from the tags by one rule, so it's consistent across the ten taggers (who read "partial"
// differently for footage). Each tagger's own call is kept as feasible_agent.
function feasible(t) {
  if (t.medium === 'blank') return 'unknown';
  if (t.medium.startsWith('live_')) return 'no';                               // needs a camera
  if (t.medium === 'render_3d') return t.feasible_agent === 'no' ? 'no' : 'partial';   // photoreal (no) vs stylised (2.5D can approximate)
  if (t.medium === 'ui_screen') return 'partial';                              // needs the real recording, or a rebuilt UI
  return t.bg === 'photo' ? 'partial' : 'yes';                                  // designed 2D; over a photo, it needs that photo
}

const { videos } = JSON.parse(readFileSync(`${DIR}/catalog.json`, 'utf8'));
const bySlug = new Map(videos.map(v => [v.slug, v]));
const tags = new Map(), errors = [];
for (const f of readdirSync(`${DIR}/tags`).filter(f => /^g\d{3}\.json$/.test(f)).sort()) {
  const want = JSON.parse(readFileSync(`${DIR}/grids/${f}`, 'utf8'));
  let got; try { got = JSON.parse(readFileSync(`${DIR}/tags/${f}`, 'utf8')); } catch (e) { errors.push(`${f}: not JSON (${e.message})`); continue; }
  if (!Array.isArray(got) || got.length !== want.length) { errors.push(`${f}: ${got.length} tags for ${want.length} cells`); continue; }
  got.forEach((t, i) => {
    if (t.slug !== want[i]) errors.push(`${f} cell ${i + 1}: slug ${t.slug}, grid has ${want[i]}`);
    for (const [k, vals] of Object.entries(ENUM)) if (!vals.includes(t[k])) errors.push(`${f} cell ${i + 1}: ${k} = ${JSON.stringify(t[k])}`);
    if (!Array.isArray(t.overlays) || t.overlays.some(o => !OVERLAYS.includes(o))) errors.push(`${f} cell ${i + 1}: overlays = ${JSON.stringify(t.overlays)}`);
    if (tags.has(want[i])) errors.push(`${want[i]} tagged twice`);
    const tag = { medium: t.medium, overlays: [...new Set(t.overlays || [])], bg: t.bg, text: t.text, feasible_agent: t.feasible, note: String(t.note || '').slice(0, 120) };
    tags.set(want[i], { ...tag, feasible: feasible(tag) });
  });
}
const untagged = videos.filter(v => !tags.has(v.slug)).map(v => v.slug), stray = [...tags.keys()].filter(s => !bySlug.has(s));
if (untagged.length) errors.push(`${untagged.length} untagged: ${untagged.slice(0, 30).join(', ')}${untagged.length > 30 ? ' …' : ''}`);
if (stray.length) errors.push(`tags for slugs not in the catalog: ${stray.join(', ')}`);
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

// ---------- breakdown ----------
const N = videos.length, pct = n => `${(100 * n / N).toFixed(1)}%`;
const count = (key, list = videos) => { const c = {}; for (const v of list) { const k = key(v); for (const x of [].concat(k)) c[x] = (c[x] || 0) + 1; } return Object.entries(c).sort((a, b) => b[1] - a[1]); };
const T = v => tags.get(v.slug);
const table = (head, rows) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(r => `| ${r.join(' | ')} |`)].join('\n');
const med = a => { const s = a.filter(Boolean).sort((x, y) => x - y); return s.length ? s[s.length >> 1] : null; };
const mmss = s => s == null ? '–' : `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
const cats = count(v => v.category).map(([c]) => c), media = ENUM.medium;

writeFileSync(`${DIR}/visual.json`, JSON.stringify(Object.fromEntries(videos.map(v => [v.slug, T(v)])), null, 0).replace(/\},"/g, '},\n"'));
writeFileSync(`${DIR}/visual.md`, [
  `# What Ships: visual breakdown of the whole catalog`, ``,
  `Every one of the ${N} launch videos, tagged from its poster frame (one frame per film, so this describes how films`,
  `look, not everything that happens in them). Generated by scripts/whatships_tags.mjs from refs/whatships/tags/;`,
  `per-film tags are in visual.json. Taxonomy: plan.md, Phase 0.`, ``,
  `## Primary medium`, ``,
  table(['medium', 'films', 'share', 'median length'], count(v => T(v).medium).map(([m, n]) => [m, n, pct(n), mmss(med(videos.filter(v => T(v).medium === m).map(v => v.seconds)))])), ``,
  `## Can code make it?`, ``,
  `Derived by one rule from the tags (scripts/whatships_tags.mjs): live footage → no; photoreal 3D → no, stylised 3D →`,
  `partial; plain screen recordings → partial; designed UI, type, 2D, abstract and illustration → yes, or partial over a photo.`, ``,
  table(['feasible', 'films', 'share'], count(v => T(v).feasible).map(([f, n]) => [f, n, pct(n)])), ``,
  `## Medium by category`, ``,
  table(['category', ...media], cats.map(c => { const l = videos.filter(v => v.category === c); return [`${c} (${l.length})`, ...media.map(m => l.filter(v => T(v).medium === m).length)]; })), ``,
  `## Feasible by category`, ``,
  table(['category', 'yes', 'partial', 'no', 'unknown'], cats.map(c => { const l = videos.filter(v => v.category === c); return [`${c} (${l.length})`, ...['yes', 'partial', 'no', 'unknown'].map(f => `${l.filter(v => T(v).feasible === f).length}`)]; })), ``,
  `## Background, text and overlays`, ``,
  table(['background', 'films', 'share'], count(v => T(v).bg).map(([k, n]) => [k, n, pct(n)])), ``,
  table(['on-screen text', 'films', 'share'], count(v => T(v).text).map(([k, n]) => [k, n, pct(n)])), ``,
  table(['overlay', 'films', 'share'], count(v => T(v).overlays).map(([k, n]) => [k, n, pct(n)])), ``,
  `## Aspect ratio by medium`, ``,
  table(['medium', 'landscape', 'square', 'portrait', 'unknown'], media.map(m => { const l = videos.filter(v => T(v).medium === m); return [m, ...['landscape', 'square', 'portrait', undefined].map(a => l.filter(v => v.aspect === a).length)]; })), ``,
].join('\n'));
console.log(`tagged ${tags.size}/${N}: all present, all valid → ${DIR}/visual.json, visual.md`);
for (const [m, n] of count(v => T(v).medium)) console.log(`  ${m.padEnd(13)} ${String(n).padStart(4)}  ${pct(n)}`);
