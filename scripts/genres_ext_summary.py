"""genres_ext_summary.py: the measured structure and craft of each new genre (refs/genres_ext/measure/, beats/), next to
the launch-film top tier (refs/whatships/craft/) so the differences are explicit. Writes refs/genres_ext/measured.md.
Fails if a measured film has no beats file, or a beats file is malformed.
  python3 scripts/genres_ext_summary.py
"""
import json, glob, os, sys, collections
import numpy as np

R = 'refs/genres_ext'
KINDS = {
    'explainers': ['hook', 'question', 'context', 'explanation', 'example', 'analogy', 'data', 'recap', 'cta', 'title', 'transition', 'other'],
    'tutorials': ['intro', 'goal', 'overview', 'step', 'result', 'tip', 'recap', 'outro', 'title', 'transition', 'other'],
    'data_stories': ['hook', 'context', 'chart_reveal', 'comparison', 'map', 'zoom', 'insight', 'story', 'conclusion', 'source', 'title', 'transition', 'other'],
    'lyric_videos': ['intro', 'verse', 'pre_chorus', 'chorus', 'bridge', 'instrumental', 'outro', 'title', 'other'],
}
q = lambda a, p=50: (round(float(np.percentile([x for x in a if x is not None], p)), 2) if [x for x in a if x is not None] else None)
mq = lambda a, u='': f'{q(a)}{u} ({q(a, 25)}–{q(a, 75)})' if q(a) is not None else '–'
pct = lambda n, d: f'{100 * n / d:.0f}%' if d else '–'

def craft(fs):
    mv = [m for f in fs for m in f['moves'] if m['dur'] <= 2.5]; secs = sum(f.get('analysed_s', f['duration']) for f in fs)
    A = [f['audio'] for f in fs if f.get('audio') and f['audio'].get('bpm')]; st = [s for f in fs for s in f['stills']]
    return {
        'moves per 10 s': mq([len([m for m in f['moves'] if m['dur'] <= 2.5]) / f.get('analysed_s', f['duration']) * 10 for f in fs]),
        'move length': mq([m['dur'] for m in mv], ' s'),
        'easing centre': mq([m['centroid'] for m in mv]),
        'hold length': mq([h for f in fs for h in f['holds']], ' s'),
        'holds ≥ 2 s': pct(sum(h >= 2 for f in fs for h in f['holds']), sum(len(f['holds']) for f in fs)),
        'hard cuts per minute': mq([len(f['cuts']) / f.get('analysed_s', f['duration']) * 60 for f in fs]),
        'contrast': mq([s['contrast'] for s in st], ':1'),
        'saturation': mq([s['saturation'] for s in st]),
        'light background': pct(sum(s['bg_luminance'] > .5 for s in st), len(st)),
        'sound': pct(sum(bool(f.get('audio') and f['audio'].get('has_sound')) for f in fs), len(fs)),
        'tempo': mq([a['bpm'] for a in A], ' BPM'),
        'cuts on the beat (vs chance)': f"{q([a['cuts_on_beat'] for a in A])} vs {q([a['chance_on_beat'] for a in A])}",
        'moves on the beat (vs chance)': f"{q([a['moves_on_beat'] for a in A])} vs {q([a['chance_on_beat'] for a in A])}",
    }

top = [json.load(open(f)) for f in glob.glob('refs/whatships/craft/*.json')]; top = [f for f in top if not f.get('error')]
TOP = craft(top)
errs, G = [], {}
for g in KINDS:
    fs = [json.load(open(f)) for f in sorted(glob.glob(f'{R}/measure/{g}/*.json')) if not f.endswith('.structure.json')]
    CUR = json.load(open(f'{R}/curation.json'))['exclude'] if os.path.exists(f'{R}/curation.json') else {}
    fs = [f for f in fs if not f.get('error') and f['id'] not in CUR.get(g, {})]   # curation: films that don't fit the genre
    B = {}
    for f in fs:
        # a film listed in two genres has a genre-specific beats file (<id>.<genre>.json) for its second listing
        p = f'{R}/beats/{f["id"]}.{g}.json' if os.path.exists(f'{R}/beats/{f["id"]}.{g}.json') else f'{R}/beats/{f["id"]}.json'
        if not os.path.exists(p): errs.append(f'{g}/{f["id"]}: no beats'); continue
        try: b = json.load(open(p))
        except Exception as e: errs.append(f'{p}: {e}'); continue
        for x in b.get('beats', []):
            if x.get('kind') not in KINDS[g]: errs.append(f'{p}: kind {x.get("kind")}')
        B[f['id']] = b
    G[g] = (fs, B)
if errs: print('\n'.join(errs[:40])); sys.exit(1)

rows = list(TOP)
L = ['# New genres: measured structure and craft', '',
     'Each genre\'s reference films (refs/genres_ext/index.md) measured with the launch-film instruments: frame differences at',
     '24 fps over the first 180 s (moves, easing, holds, cuts), the whole soundtrack (tempo, beat sync), stills (contrast,',
     'colour), and a vision pass over one-frame-a-few-seconds sheets for structure. Videos were downloaded to a temp file,',
     'measured and deleted. Medians (middle half). Generated by scripts/genres_ext_summary.py. Films that don\'t fit their',
     'genre (maths animations among the data stories, teasers among the tutorials, music videos among the lyric videos) are',
     'left out, with reasons, per refs/genres_ext/curation.json.', '',
     '**Tempo and beat rows for explainers, tutorials and data stories measure the narration, not music**: their soundtracks',
     'are mostly voice-over, so the onset rhythm is speech (hence 150–160 "BPM"). Read those rows only for lyric videos and',
     'launch films. Motion rows cover the first 180 s of each film; long films are sampled more coarsely in the beat pass.', '',
     '| measure | launch top tier | ' + ' | '.join(G) + ' |', '|---|---|' + '---|' * len(G)]
C = {g: craft(fs) for g, (fs, _) in G.items()}
for r in rows: L.append(f'| {r} | {TOP[r]} | ' + ' | '.join(C[g][r] for g in G) + ' |')
L.append('| films measured | 36 | ' + ' | '.join(str(len(fs)) for fs, _ in G.values()) + ' |')
L.append('| film length | – | ' + ' | '.join(mq([f['duration'] for f in fs], ' s') for fs, _ in G.values()) + ' |')
for g, (fs, B) in G.items():
    bs = list(B.values()); n = len(bs)
    lens = [x['end'] - x['start'] for b in bs for x in b['beats'] if x['kind'] not in ('transition',)]
    kinds = collections.Counter(k for b in bs for k in set(x['kind'] for x in b['beats']))
    opens = collections.Counter(b['beats'][0]['kind'] for b in bs if b['beats'])
    tr = collections.Counter(t for b in bs for t in b.get('transitions', [])); cam = collections.Counter(c for b in bs for c in b.get('camera', []))
    pace = collections.Counter(b.get('pace') for b in bs)
    top_ = lambda c: ', '.join(f'{k} {pct(v, n)}' for k, v in c.most_common(8))
    gf = [b.get('genre_fields', {}) for b in bs]
    L += ['', f'## {g} ({n} films)', '',
          f'- Beats: median {mq(lens, " s")} each, {q([len([x for x in b["beats"] if x["kind"] != "transition"]) for b in bs])} per film.',
          f'- Opens with: {top_(opens)}.', f'- Films containing each beat kind: {top_(kinds)}.',
          f'- First text at {mq([b.get("first_text_s") for b in bs], " s")}; title cards per film {q([b.get("text_cards") for b in bs])}.',
          f'- Transitions: {top_(tr)}.', f'- Camera: {top_(cam)}.', f'- Pace: {top_(pace)}.']
    keys = sorted({k for x in gf for k in x})
    for k in keys:
        vals = [x.get(k) for x in gf if k in x]
        if all(isinstance(v, bool) for v in vals): L.append(f'- {k}: {pct(sum(vals), len(vals))} of films.')
        elif all(isinstance(v, (int, float)) and not isinstance(v, bool) for v in vals): L.append(f'- {k}: {mq(vals)}.')
        elif all(isinstance(v, list) for v in vals): L.append(f'- {k}: ' + ', '.join(f'{a} {pct(c, len(vals))}' for a, c in collections.Counter(a for v in vals for a in v).most_common(8)) + '.')
        else: L.append(f'- {k}: ' + ', '.join(f'{a} {pct(c, len(vals))}' for a, c in collections.Counter(map(str, vals)).most_common(6)) + '.')
    if g == 'lyric_videos':   # song structure from the audio (scripts/lyric_structure.py)
        S = [json.load(open(p)) for p in glob.glob(f'{R}/measure/{g}/*.structure.json')]; S = [x for x in S if not x.get('error')]
        rng = np.random.default_rng(7); near, chance = [], []
        for x in S:
            mm = next((f for f in fs if f['id'] == x['id']), None)
            if not mm or not mm['cuts']: continue
            cuts = np.array(mm['cuts']); A = mm['analysed_s']; bnd = [sg['start'] for sg in x['segments'][1:] if 2 < sg['start'] < A - 2]
            if not bnd: continue
            hit = lambda t: bool((np.abs(cuts - t) <= 1).any())
            near.append(np.mean([hit(t) for t in bnd])); chance.append(np.mean([hit(t) for t in rng.uniform(2, A - 2, 400)]))
        L += [f'- Song structure from the audio ({len(S)} songs): {q([x["sections"] for x in S])} sections of {mq([sg["end"] - sg["start"] for x in S for sg in x["segments"]], " s")}; '
              f'about {q([x["groups"] for x in S])} kinds of section per song. (Chorus share and first-chorus time were calibration targets for the detector, not findings.)',
              f'- Section changes with a hard cut within 1 s: {q(near)} of changes, against {q(chance)} at random moments ({len(near)} films): lyric videos don\'t cut on song sections more than chance.']
    seq = lambda b: ' → '.join(k for i, k in enumerate(x['kind'] for x in b['beats'] if x['kind'] != 'transition') if i == 0 or k != [x['kind'] for x in b['beats'] if x['kind'] != 'transition'][i - 1])
    title = {f['id']: f['title'] for f in fs}
    L += ['', 'Structures (repeats merged):', ''] + [f'- {title.get(i, i)[:50]}: {seq(b)[:220]}' for i, b in list(B.items())[:10]]
open(f'{R}/measured.md', 'w').write('\n'.join(L) + '\n')

# the same numbers, machine-readable, for the web app's catalog (web/scripts/build-catalog.mjs)
J = {}
for g, (fs, B) in G.items():
    bs = list(B.values()); st = [x for f in fs for x in f['stills']]
    gf = [b.get('genre_fields', {}) for b in bs]
    last = collections.Counter(b['beats'][-1]['kind'] for b in bs if b['beats'])
    films = [{k: v for k, v in f.items() if k in ('title', 'creator', 'url', 'duration', 'medium')} for f in fs]
    ver = {x['url']: x for x in json.load(open(f'{R}/{g}.verified.json'))['films']} if os.path.exists(f'{R}/{g}.verified.json') else {}
    for f in films:
        v = ver.get(f['url'], {}); f.update({'year': v.get('year'), 'subject': v.get('subject', ''), 'notes': v.get('notes', ''), 'signal': v.get('quality_signal', '')})
    J[g] = {
        'films': len(fs), 'length': q([f['duration'] for f in fs]),
        'shot': q([f.get('analysed_s', f['duration']) / (len(f['cuts']) + 1) for f in fs]),
        'cutsPerMin': q([len(f['cuts']) / f.get('analysed_s', f['duration']) * 60 for f in fs]),
        'beat': q([x['end'] - x['start'] for b in bs for x in b['beats'] if x['kind'] != 'transition']),
        'beats': q([len([x for x in b['beats'] if x['kind'] != 'transition']) for b in bs]),
        'hold': q([h for f in fs for h in f['holds']]),
        'light': round(100 * sum(x['bg_luminance'] > .5 for x in st) / len(st), 1) if st else None,
        'lastBeat': dict(last.most_common(3)), 'lastBeatShare': round(100 * last.most_common(1)[0][1] / len(bs), 1) if bs else None,
        'cursor': round(100 * sum(bool(x.get('cursor_visible')) for x in gf) / len(gf), 1) if gf and any('cursor_visible' in x for x in gf) else 0,
        'reference': films,
    }
json.dump(J, open(f'{R}/measured.json', 'w'), indent=1)
print('\n'.join(L[:40]))
