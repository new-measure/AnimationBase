// whatships_genres.mjs: groups every film in the catalog into a visual family (from its poster tags in visual.json) and
// picks 16 representatives per family, spread across categories, for studying (plan.md, Phase 0). Writes
// refs/whatships/genres.json (family → every slug) and refs/whatships/genres.md (counts, representatives with their
// original X links), plus a numbered 4 × 4 grid per family in refs/whatships/genre_grids/ (gitignored) to look at.
//   node scripts/whatships_genres.mjs [--chrome=<path>]
import puppeteer from 'puppeteer-core';
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

const args = Object.fromEntries(process.argv.slice(2).map(a => { const [k, v] = a.replace(/^--/, '').split('='); return [k, v ?? true]; }));
const DIR = 'refs/whatships', OUT = `${DIR}/genre_grids`;
const { videos } = JSON.parse(readFileSync(`${DIR}/catalog.json`, 'utf8'));
const vis = JSON.parse(readFileSync(`${DIR}/visual.json`, 'utf8'));

// Visual families, in the order the plan's genre docs follow. A poster is one frame, so these describe how a film
// looks, not its structure; the structure and pacing notes come from studying the representatives.
const FAMILIES = [
  ['ui_walkthrough', 'Product UI walkthrough', t => t.medium === 'ui_polished'],
  ['screen_demo', 'Screen-recording demo', t => t.medium === 'ui_screen'],
  ['type_led', 'Type-led announcement', t => t.medium === 'kinetic_type' && t.bg !== 'photo'],
  ['type_over_footage', 'Type over footage', t => t.medium === 'kinetic_type' && t.bg === 'photo'],
  ['brand_graphic', 'Brand and graphic motion', t => t.medium === 'graphic_2d'],
  ['abstract', 'Abstract and atmospheric', t => t.medium === 'abstract'],
  ['illustrated', 'Illustrated and character', t => t.medium === 'illustration'],
  ['stylised_3d', '3D product and scene', t => t.medium === 'render_3d'],
  ['founder_talk', 'People on camera', t => t.medium === 'live_people'],
  ['product_footage', 'Product footage', t => t.medium === 'live_product'],
  ['cinematic_broll', 'Cinematic b-roll', t => t.medium === 'live_scene'],
  ['unclassified', 'Blank first frame', t => t.medium === 'blank'],
];
const fam = {}; for (const [k] of FAMILIES) fam[k] = [];
for (const v of videos) {
  const t = vis[v.slug]; if (!t) { console.error(`no tags for ${v.slug}: run whatships_tags.mjs`); process.exit(1); }
  const f = FAMILIES.find(([, , test]) => test(t)); if (!f) { console.error(`no family for ${v.slug}: ${JSON.stringify(t)}`); process.exit(1); }
  fam[f[0]].push(v);
}

// 16 representatives: round-robin across categories, typical lengths first (10 s – 2 min), deterministic.
const hash = s => { let h = 2166136261; for (const c of s) h = Math.imul(h ^ c.charCodeAt(0), 16777619); return h >>> 0; };
function reps(list, n = 16) {
  const typical = v => v.seconds >= 10 && v.seconds <= 120;
  const byCat = {}; for (const v of [...list].sort((a, b) => (typical(b) - typical(a)) || hash(a.slug) - hash(b.slug))) (byCat[v.category] ||= []).push(v);
  const cats = Object.keys(byCat).sort((a, b) => byCat[b].length - byCat[a].length), out = [];
  while (out.length < Math.min(n, list.length)) for (const c of cats) if (byCat[c].length && out.length < n) out.push(byCat[c].shift());
  return out;
}

const N = videos.length, mmss = s => s ? `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}` : '–';
const med = l => { const s = l.map(v => v.seconds).filter(Boolean).sort((a, b) => a - b); return s[s.length >> 1]; };
const pick = {}; for (const [k] of FAMILIES) pick[k] = reps(fam[k]);
writeFileSync(`${DIR}/genres.json`, JSON.stringify(Object.fromEntries(FAMILIES.map(([k, name]) => [k, { name, count: fam[k].length, representatives: pick[k].map(v => v.slug), slugs: fam[k].map(v => v.slug) }])), null, 1));
const feas = l => ['yes', 'partial', 'no'].map(f => l.filter(v => vis[v.slug].feasible === f).length).join(' / ');
writeFileSync(`${DIR}/genres.md`, [
  `# What Ships: visual families`, ``,
  `Every film in the catalog (${N}) sorted into one visual family by its poster tags (visual.json). Generated by`,
  `scripts/whatships_genres.mjs. Recipes per family are in docs/genres/.`, ``,
  `| family | films | share | median length | code can make it: yes / partial / no |`, `|---|---|---|---|---|`,
  ...FAMILIES.map(([k, name]) => `| ${name} (\`${k}\`) | ${fam[k].length} | ${(100 * fam[k].length / N).toFixed(1)}% | ${mmss(med(fam[k]))} | ${feas(fam[k])} |`), ``,
  ...FAMILIES.flatMap(([k, name]) => [`## ${name} (${fam[k].length})`, ``, `Representatives (grid \`genre_grids/${k}.jpg\`, cells in this order):`, ``,
    ...pick[k].map((v, i) => `${i + 1}. [${v.title}](${v.url}) — ${v.company} · ${v.category} · ${mmss(v.seconds)} · [X](${v.x}) — ${vis[v.slug].note}`), ``]),
].join('\n'));

// grids to look at
mkdirSync(OUT, { recursive: true });
const CHROME = [args.chrome, process.env.CHROME_PATH, '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', '/usr/bin/google-chrome', '/usr/bin/chromium'].find(p => p && existsSync(p));
const browser = await puppeteer.launch({ executablePath: CHROME, headless: true, args: ['--allow-file-access-from-files'] });
const page = await browser.newPage(); await page.goto(pathToFileURL(resolve(DIR)).href + '/');
for (const [k, name] of FAMILIES) {
  if (!pick[k].length) continue;
  const url = await page.evaluate(async (srcs, label) => {
    const CW = 480, CH = 270, c = document.createElement('canvas'); c.width = 4 * CW; c.height = Math.ceil(srcs.length / 4) * CH; const x = c.getContext('2d');
    x.fillStyle = '#777'; x.fillRect(0, 0, c.width, c.height);
    for (let i = 0; i < srcs.length; i++) {
      const img = new Image(); img.src = srcs[i]; await img.decode();
      const cx = (i % 4) * CW, cy = Math.floor(i / 4) * CH, s = Math.min((CW - 4) / img.width, (CH - 4) / img.height);
      x.fillStyle = '#000'; x.fillRect(cx + 2, cy + 2, CW - 4, CH - 4);
      x.drawImage(img, cx + (CW - img.width * s) / 2, cy + (CH - img.height * s) / 2, img.width * s, img.height * s);
      x.fillStyle = '#FFE14D'; x.fillRect(cx + 2, cy + 2, 46, 34); x.fillStyle = '#000'; x.font = 'bold 26px sans-serif'; x.fillText(String(i + 1), cx + 8, cy + 29);
    }
    x.fillStyle = '#FFE14D'; x.font = 'bold 20px sans-serif'; x.fillText(label, 10, c.height - 10);
    return c.toDataURL('image/jpeg', .88);
  }, pick[k].map(v => `posters/${v.slug}.webp`), name);
  writeFileSync(`${OUT}/${k}.jpg`, Buffer.from(url.split(',')[1], 'base64'));
}
await browser.close();
console.log(`families → ${DIR}/genres.json, genres.md, ${OUT}/`);
for (const [k, name] of FAMILIES) console.log(`  ${name.padEnd(28)} ${String(fam[k].length).padStart(4)}`);
